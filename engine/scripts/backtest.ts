/**
 * Replays Cyclone Michaung, 4 December 2023, through the engine for every locality in
 * `chennai-places.json` and compares the result with localities that relief agencies and
 * the press documented as flooded.
 *
 * The replay uses the rain on record, not a forecast, so this tests the part of the model
 * that judges places. It says nothing about forecast skill; `trackRecord` measures that.
 *
 *   npm run backtest            prints the table
 *   npm run backtest -- --write also writes docs/backtest.md
 */
import { writeFileSync } from 'node:fs';
import { MemoryRepository } from '../src/api/repository.ts';
import { assessPlace, type ServiceDependencies } from '../src/api/service.ts';
import type { Assessment, Level } from '../src/core/types.ts';
import placesData from '../src/data/chennai-places.json' with { type: 'json' };
import { fetchForecast, fetchForecastHistory, fetchReplay, fetchTerrain } from '../src/sources/open-meteo.ts';

const DATE = process.argv.find((arg) => /^\d{4}-\d{2}-\d{2}$/.test(arg)) ?? '2023-12-04';
const PAUSE_MS = 1500;
const MICHAUNG = '2023-12-04';

const SPHERE = 'https://www.sphereindia.org.in/sites/default/files/2023-12/SitRep3_CycloneMichaung_09-12-23.pdf';
const CITIZEN_MATTERS = 'https://citizenmatters.in/devastation-storm-chennai-cyclone-michaung-monsoon-flooding-36477';
const PTI = 'https://www.theweek.in/wire-updates/national/2023/12/07/mds3-tn-rains-situation.html';
const DECCAN_HERALD =
  'https://www.deccanherald.com/india/tamil-nadu/floating-cars-submerged-localities-chennai-battles-floods-in-the-wake-of-cyclone-michuang-2796547';

/** Localities named as flooded, with the report that names them. */
const DOCUMENTED: Record<string, string> = {
  Velachery: SPHERE,
  Pallikaranai: SPHERE,
  'West Tambaram': PTI,
  Mambalam: SPHERE,
  Mylapore: SPHERE,
  Kodambakkam: SPHERE,
  Nungambakkam: SPHERE,
  'Anna Nagar': SPHERE,
  Perungudi: SPHERE,
  Choolaimedu: SPHERE,
  Semmancheri: SPHERE,
  Pulianthope: SPHERE,
  Madipakkam: CITIZEN_MATTERS,
  Medavakkam: DECCAN_HERALD,
  Perambur: DECCAN_HERALD,
  Adyar: DECCAN_HERALD,
  Manali: PTI,
};

interface Row {
  readonly name: string;
  readonly assessment: Assessment;
  readonly source?: string;
}

const LEVEL_ORDER: readonly Level[] = ['SEVERE', 'HIGH', 'WATCH', 'LOW'];

const deps: ServiceDependencies = {
  repository: new MemoryRepository(),
  fetchForecast,
  fetchReplay,
  fetchTerrain,
  fetchForecastHistory,
  now: () => new Date(),
  newId: () => 'backtest',
};

async function main(): Promise<void> {
  const rows: Row[] = [];
  for (const place of placesData.places) {
    const assessment = await assessPlace(deps, { lat: place.lat, lon: place.lon }, DATE);
    // Open-Meteo counts each elevation point against a per-minute limit.
    await new Promise((resolve) => setTimeout(resolve, PAUSE_MS));
    const source = DATE === MICHAUNG ? DOCUMENTED[place.name] : undefined;
    rows.push({ name: place.name, assessment, ...(source === undefined ? {} : { source }) });
  }
  rows.sort(
    (a, b) => LEVEL_ORDER.indexOf(a.assessment.level) - LEVEL_ORDER.indexOf(b.assessment.level) || a.name.localeCompare(b.name),
  );

  const documented = rows.filter((row) => row.source !== undefined);
  const flagged = documented.filter((row) => row.assessment.level === 'SEVERE' || row.assessment.level === 'HIGH');
  const missing = Object.keys(DOCUMENTED).filter((name) => !rows.some((row) => row.name === name));
  const counts = LEVEL_ORDER.map((level) => `${level} ${String(rows.filter((row) => row.assessment.level === level).length)}`).join(', ');

  const highOrSevere = rows.filter((row) => row.assessment.level === 'SEVERE' || row.assessment.level === 'HIGH').length;
  const missed = documented.filter((row) => !flagged.includes(row)).map((row) => row.name);
  const isMichaung = DATE === MICHAUNG;

  const lines = [
    `# Backtest: ${isMichaung ? 'Cyclone Michaung, ' : ''}${DATE}`,
    '',
    `What Vellam says about each Chennai locality when it is given the rain that fell on ${DATE}.`,
    'Generated by `npm run backtest -- --write`; do not edit by hand.',
    '',
    '## Result',
    '',
    `- Localities assessed: **${String(rows.length)}** (${counts}).`,
    ...(isMichaung
      ? [
          `- Named as flooded by relief agencies or the press, and in the list: **${String(documented.length)}**. Vellam rated **${String(flagged.length)}** of them HIGH or SEVERE.`,
          ...(missed.length > 0 ? [`- Missed: **${missed.join(', ')}**, rated below HIGH although documented as flooded.`] : []),
          `- Vellam rated ${String(highOrSevere)} of all ${String(rows.length)} localities HIGH or SEVERE, so catching the documented ones is weak evidence on its own: a rule that warned everyone would have caught them too. This storm flooded most of the city, and the replay cannot show whether Vellam would have stayed quiet where it should.`,
          ...(missing.length > 0 ? [`- Documented but not in the locality list, so not assessed: ${missing.join(', ')}.`] : []),
        ]
      : ['- No list of flooded localities was collected for this date, so this replay shows how the levels spread, not how accurate they were.']),
    '',
    '## What this does and does not show',
    '',
    '- The replay uses rain from the historical record, so it tests how Vellam judges a place,',
    '  not how good the forecast was.',
    '- Each locality is assessed at one point, its centre on OpenStreetMap. Flooding varies street',
    '  by street, so a locality rated WATCH can still contain streets that flooded.',
    '- A locality with no report is not a locality that stayed dry. Reports name the worst hit',
    '  places, so the table cannot measure false alarms.',
    '- The record is a weather model reanalysis and reads lower than rain gauges did.',
    '',
    '## Every locality',
    '',
    '| Locality | Vellam | Rain in worst 24 h | Factors | Documented as flooded |',
    '|---|---|---|---|---|',
    ...rows.map((row) => {
      const wettest = Math.max(...row.assessment.windows.map((w) => w.trailing24hMm));
      const factors = row.assessment.factors.map((f) => f.title).join('; ') || 'none';
      const documentedCell = row.source === undefined ? '' : `[yes](${row.source})`;
      return `| ${row.name} | ${row.assessment.level} | ${String(wettest)} mm | ${factors} | ${documentedCell} |`;
    }),
    '',
  ];

  console.log(lines.join('\n'));
  if (process.argv.includes('--write')) writeFileSync(new URL(`../../docs/backtest-${DATE}.md`, import.meta.url), lines.join('\n'));
}

await main();
